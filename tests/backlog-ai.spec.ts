import {test,expect} from '@playwright/test'
import {createSeed} from '../src/seed'
async function setup(page:import('@playwright/test').Page,count:number,slow=false){
 const seed=createSeed(),base=seed.items[0]
 seed.items=Array.from({length:count},(_,i)=>({...base,id:`batch-${i}`,title:`Очередь теста ${i}${slow?' Долгий Codex':i===count-1?' Сбой Codex':''}`,body:i?'Синтетическое описание для проверки очереди.':'',lane:'backlog' as const,parentId:null,sprintId:null,relatedIds:[],attachments:[],stickers:[],scores:{},priorityScore:2,matrixBucket:'research-next' as const}))
 seed.comments=[]
 await page.request.post('/__test/reset',{data:seed})
 await page.request.post('/__test/research-mode',{data:{mode:'codex',web:true,concepts:true}})
 await page.goto('/');await page.getByRole('button',{name:'Бэклог',exact:true}).click()
 return (await page.request.get('/api/state')).json()
}
test('весь бэклог: очередь, перезагрузка, сортировка предложений и отдельное подтверждение',async({page},info)=>{
 test.setTimeout(90000)
 const before=await setup(page,39)
 await page.getByRole('button',{name:'Действия бэклога',exact:true}).click()
 const start=page.getByRole('button',{name:'Переоценить бэклог',exact:true})
 await expect(start).toBeEnabled();await start.click()
 await expect(page.getByRole('button',{name:'Остановить',exact:true})).toBeVisible()
 await page.reload();await page.getByRole('button',{name:'Бэклог',exact:true}).click()
 await page.getByRole('button',{name:'Действия бэклога',exact:true}).click()
 await expect(start).toBeDisabled()
 await expect.poll(async()=>((await(await page.request.get('/api/backlog/trendwatch')).json()).batch?.completed),{timeout:65000}).toBe(39)
 await expect(start).toBeEnabled()
 const result=await(await page.request.get('/api/backlog/trendwatch')).json()
 expect(result.batch.ready).toBe(38);expect(result.batch.failed).toBe(1)
 expect(await(await page.request.get('/api/state')).json()).toEqual(before)
 await page.getByLabel('Сортировка бэклога').selectOption('ai')
 const matrix=page.locator('.matrix-card')
 await expect(matrix).toHaveCount(39)
 await expect(matrix.last()).toContainText('Без оценки ИИ')
 const titles=await matrix.locator('.backlog-title').allTextContents()
 const scores=titles.slice(0,-1).map(t=>Number(t.match(/Очередь теста (\d+)/)![1])%11)
 expect(scores).toEqual([...scores].sort((a,b)=>b-a))
 await page.screenshot({path:`output/playwright/backlog-ai-${info.project.name}.png`})
 await matrix.first().locator('.ai-score-button').click()
 const modal=page.getByRole('dialog',{name:'Рекомендация ИИ',exact:true})
 await expect(modal.getByRole('combobox')).toHaveCount(0)
 await expect(modal.getByLabel('Оценка приоритета')).toHaveValue('10')
 await modal.getByLabel('Оценка приоритета').fill('8')
 await modal.getByRole('button',{name:'Подтвердить',exact:true}).click()
 await expect(modal).toHaveCount(0)
 const after=await(await page.request.get('/api/state')).json()
 expect(after.items.filter((i:{priorityScore:number})=>i.priorityScore===8)).toHaveLength(1)
 expect(after.items.filter((i:{priorityScore:number})=>i.priorityScore===2)).toHaveLength(38)
 expect(after.items.every((i:{lane:string})=>i.lane==='backlog')).toBe(true)
 expect(after.items.every((i:{matrixBucket:string})=>i.matrixBucket==='research-next')).toBe(true)
 await page.getByRole('button',{name:'Список',exact:true}).click()
 await expect(page.locator('.backlog-table tbody tr').last()).toContainText('Без оценки ИИ')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBe(0)
})
test('остановка очереди и защита API',async({page})=>{
 const before=await setup(page,5,true)
 expect((await page.request.post('/api/backlog/trendwatch',{headers:{Origin:'https://unrelated.example'},data:{requestId:crypto.randomUUID()}})).status()).toBe(403)
 await page.getByRole('button',{name:'Действия бэклога',exact:true}).click()
 await page.getByRole('button',{name:'Переоценить бэклог',exact:true}).click()
 await page.getByRole('button',{name:'Остановить',exact:true}).click()
 await expect.poll(async()=>((await(await page.request.get('/api/backlog/trendwatch')).json()).batch?.active)).toBe(false)
 const result=await(await page.request.get('/api/backlog/trendwatch')).json()
 expect(result.batch.cancelled).toBe(5)
 expect(await(await page.request.get('/api/state')).json()).toEqual(before)
 await page.request.post('/__test/portal',{data:{session:'none'}})
 expect((await page.request.get('/api/backlog/trendwatch')).status()).toBe(401)
})

test('review lifecycle UI: unscored tasks stay unreviewed, red attention and lead decisions preserve scores',async({page},info)=>{
 const seed=createSeed(),base=seed.items[0],now=Date.now()
 seed.items=[
  {...base,id:'due-task',title:'Задача на пересмотр',body:'Синтетическая проверка',lane:'backlog',sprintId:null,parentId:null,relatedIds:[],attachments:[],stickers:[],scores:{},priorityScore:5,matrixBucket:'research-next',priorityReview:{reviewedAt:now-31*86400000}},
  {...base,id:'zero-task',title:'Нулевой приоритет',body:'',lane:'backlog',sprintId:null,parentId:null,relatedIds:[],attachments:[],stickers:[],scores:{},priorityScore:0,matrixBucket:'take-next'},
  {...base,id:'unknown-task',title:'Без оценки',body:'',lane:'backlog',sprintId:null,parentId:null,relatedIds:[],attachments:[],stickers:[],scores:{},priorityScore:undefined,matrixBucket:'take-next'},
 ]
 seed.comments=[]
 await page.request.post('/__test/reset',{data:seed})
 await page.request.post('/__test/research-mode',{data:{mode:'codex',web:true,concepts:true}})
 await page.goto('/');await page.getByRole('button',{name:'Бэклог',exact:true}).click()
 const due=page.locator('.matrix-card').filter({has:page.getByRole('button',{name:'Задача на пересмотр',exact:true})})
 await expect(due).toHaveClass(/priority-review-needed/)
 await expect(due.locator('.priority-review-countdown')).toHaveText('13 дн.')
 await expect(due.locator('.priority-review-countdown')).toHaveAttribute('aria-label',/Нужен пересмотр.*До переноса/)
 const layout=await due.evaluate(e=>{
  const rect=(selector:string)=>e.querySelector(selector)!.getBoundingClientRect()
  const timer=rect('.priority-review-countdown'),title=rect('.backlog-title'),reaction=rect('.reaction-wrap'),score=rect('.backlog-score-pair'),meta=rect('.matrix-card-meta')
  return {timerRight:timer.left>=title.right,reactionLeft:reaction.left<score.left,reactionBelow:reaction.top>=meta.bottom,sameBottom:Math.abs(reaction.bottom-score.bottom)<4}
 })
 expect(layout).toEqual({timerRight:true,reactionLeft:true,reactionBelow:true,sameBottom:true})
 await expect(page.locator('.matrix-unassigned')).toContainText('Не разобрано')
 await expect(page.locator('.matrix-unassigned .matrix-card')).toHaveCount(2)
 await page.screenshot({path:`output/playwright/review-attention-${info.project.name}.png`,animations:'disabled'})
 await due.locator('.ai-score-button').click()
 const dialog=page.getByRole('dialog',{name:'Рекомендация ИИ',exact:true})
 await dialog.getByRole('button',{name:'Сбросить счётчик',exact:true}).click()
 await expect(dialog.getByRole('button',{name:'Сбросить счётчик',exact:true})).toHaveCount(0)
 await expect(due).not.toHaveClass(/priority-review-needed/)
 await expect(due.locator('.priority-review-countdown')).toHaveText('30 дн.')
 await dialog.getByRole('button',{name:'В «Не разобрано»',exact:true}).click()
 await expect(page.locator('.matrix-unassigned .matrix-card')).toHaveCount(3)
 const state=await(await page.request.get('/api/state')).json(),item=state.items.find((i:{id:string})=>i.id==='due-task')
 expect(item.priorityScore).toBe(5);expect(item.matrixBucket).toBeNull();expect(item.priorityReview.previousBucket).toBe('research-next')
 await page.screenshot({path:`output/playwright/review-lifecycle-${info.project.name}.png`})
})

