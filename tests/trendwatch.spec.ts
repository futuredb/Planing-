async function confirmAndReopen(page:Page,panel:Locator){
 const title=(await panel.locator('.ai-review-task').innerText()).trim()
 const incoming=page.locator('.inbox-list > li').filter({has:page.getByRole('button',{name:title,exact:true})})
 const wasInbox=await incoming.count()>0
 await panel.getByRole('button',{name:'Подтвердить',exact:true}).click()
 await expect(panel).toHaveCount(0)
 if(wasInbox){await expect(incoming).toHaveCount(0);await page.getByRole('button',{name:'Бэклог',exact:true}).click();await page.getByRole('button',{name:'Список',exact:true}).click()}
 const row=page.locator('.inbox-list > li:visible, .matrix-card:visible, .backlog-table tbody tr:visible, .backlog-mobile > li:visible').filter({has:page.getByRole('button',{name:title,exact:true})})
 await row.locator('.ai-score-button').click()
}


async function prepare(page:Page,title='Пилот AI-исследователя',mode='codex',web=false,concepts=false){
  await page.goto('about:blank')
  const seed=createSeed(),base=seed.items[0]
  seed.items.push({...base,id:'previous-ai',title:'AI-исследователь: прошлый пилот',body:'Синтетический результат прошлой проверки.',lane:'done',sprintId:seed.sprints[0].id,attachments:[],stickers:[],relatedIds:[],parentId:null})
  await page.request.post('/__test/reset',{data:seed})
  await page.request.post('/__test/research-mode',{data:{mode,web,concepts}})
  await page.goto('/')
  await page.getByRole('button',{name:'Входящие',exact:true}).click()
  await page.getByLabel('Название идеи').fill(title)
  await page.getByLabel('Контекст идеи').fill('Проверить пользу автоматизации обзоров зарубежных решений для дизайнеров.')
  await page.getByRole('button',{name:'Добавить',exact:true}).click()
  const card=page.locator('.inbox-list > li').filter({has:page.getByRole('button',{name:title,exact:true})})
  await card.locator('.ai-score-button').click()
  const panel=page.getByRole('dialog',{name:'Рекомендация ИИ',exact:true})
  await expect(panel.getByRole('button',{name:'Получить ИИ-рекомендацию',exact:true})).toBeEnabled()
  return panel
}

