 await page.reload();await page.getByRole('button',{name:'Бэклог',exact:true}).click()
 await page.getByRole('button',{name:'Действия бэклога',exact:true}).click()
 await page.getByRole('button',{name:'Переоценить бэклог',exact:true}).click()
